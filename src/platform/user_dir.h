// 用户目录来源腿接口（src/platform/user_dir.h）
// ------------------------------------------------------------
// SPEC.FEAT.CONN.10（SSH 密钥管理器）得先知道 `~/.ssh` 在哪儿。裁决 7.106 D10①
// 把它定成一条平台腿，而不是「把 `src/main.cpp` 里那行 std::getenv("HOME") 再
// 复制一份」：环境变量的取法本身就是平台知识（POSIX 读 `HOME`、Win32 读
// `USERPROFILE`），渗进共享路径即违 AGENTS.md §4.5 第 23 条。`main.cpp` 那行属
// 既成事实，本条**不动**（第 3 条不做等宽重构），登记为观察项随 CONN.03 的档案腿一并收。
//
// 分工：本腿只交「用户目录」这一段，`/.ssh` 的拼接、「恒在表首」与「移除请求
// 整条作废」都在纯逻辑层的 `conn::normalize_key_dirs()` 里（无头可单测）。
//
// 线程口径：只读环境变量，不碰文件系统，任何线程可调；实际调用点是 worker
// 线程上的扫盘与生成（第 25 条）。
// ============================================================

#include <string>

namespace borealis::platform {

/// @brief 当前用户的家目录（绝对路径串，原样透传环境变量，不裁尾分隔符）。
///
/// 空串是**合法结果**而不是错误：容器与服务账户可能压根没有这个环境变量。此时
/// `normalize_key_dirs()` 不追加 `~/.ssh`——宁可不扫，也不去扫一个猜出来的目录。
[[nodiscard]] auto ssh_user_dir() -> std::string;

}  // namespace borealis::platform
